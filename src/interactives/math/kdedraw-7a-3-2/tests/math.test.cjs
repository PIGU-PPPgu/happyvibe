global.window = globalThis;
require('../js/mathengine.js');
var M = window.MathEngine, assert = require('assert');
var fs = require('fs');
var src = fs.readFileSync(require('path').join(__dirname, '../js/data.js'), 'utf8');
var sb = { window: {} }; new Function('window', src)(sb.window);
var L = sb.window.LESSON;
assert.strictEqual(M.evalExpr('2x + 1', { x: 2 }), 5);
assert.strictEqual(M.evalExpr('x**2 - 1', { x: -2 }), 3, '负数平方');
assert.strictEqual(M.evalExpr('3(x + 1)', { x: 2 }), 9, '隐式乘法');
assert.strictEqual(M.evalExpr('(2x - 1) / 3', { x: 5 }), 3);
assert.strictEqual(M.evalExpr('import', { x: 1 }), null, '白名单拒绝注入');
assert.strictEqual(M.evalExpr('window', { x: 1 }), null);
assert.ok(L.quiz.every(q => q.a >= 0 && q.a < q.opts.length));
