require('../js/mathengine.js');
var M = window.MathEngine, assert = require('assert');
var fs = require('fs');
var src = fs.readFileSync(require('path').join(__dirname, '../js/data.js'), 'utf8');
var sb = { window: {} }; new Function('window', src)(sb.window);
var L = sb.window.LESSON;
assert.deepStrictEqual(M.combine([{ c: 3, e: 'x' }, { c: 5, e: 'x' }]), [{ c: 8, e: 'x' }]);
assert.deepStrictEqual(M.combine([{ c: 3, e: 'x2' }, { c: 5, e: 'x' }]).length, 2, '不同类不合');
var d = M.distribute([{ c: 2, e: 'a' }, { c: -3, e: '' }], -1);
assert.strictEqual(d[0].c, -2); assert.strictEqual(d[1].c, 3, '负号全变号');
